import kagglehub
import pandas as pd
import numpy as np
import os
from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score


# Output folder for predictions

OUTPUT_DIR = "outputs/"
os.makedirs(OUTPUT_DIR, exist_ok=True)



# Step 1: Download Dataset via KaggleHub

def download_dataset():
    """
    Download the Superstore Sales dataset using kagglehub.
    Returns the path to the downloaded CSV file.
    """
    print("[INFO] Downloading dataset from Kaggle...")
    path = kagglehub.dataset_download("rohitsahoo/sales-forecasting")
    print(f"[INFO] Dataset downloaded to: {path}")

    for file in os.listdir(path):
        if file.endswith(".csv"):
            csv_path = os.path.join(path, file)
            print(f"[INFO] Using file: {csv_path}")
            return csv_path

    raise FileNotFoundError("No CSV file found in the downloaded dataset folder.")



# Step 2: Load & Preprocess Data

def load_and_preprocess(csv_path):
    print("[INFO] Loading dataset...")
    df = pd.read_csv(csv_path, encoding="latin-1")
    print(f"[INFO] Raw shape: {df.shape}")

    # Drop high-cardinality / irrelevant ID columns
    # City & State dropped too — too many unique values, cause noise in LR
    drop_cols = ["Row ID", "Order ID", "Customer ID", "Customer Name",
                 "Product ID", "Product Name", "Postal Code",
                 "Country", "City", "State"]
    df.drop(columns=[c for c in drop_cols if c in df.columns], inplace=True)

    # Date feature engineering
    df["Order Date"] = pd.to_datetime(df["Order Date"], dayfirst=True, errors="coerce")
    df["Ship Date"]  = pd.to_datetime(df["Ship Date"],  dayfirst=True, errors="coerce")

    # Most useful signal: how many days did it take to ship?
    df["days_to_ship"] = (df["Ship Date"] - df["Order Date"]).dt.days

    # Seasonality signals
    df["order_year"]  = df["Order Date"].dt.year
    df["order_month"] = df["Order Date"].dt.month

    df.drop(columns=["Order Date", "Ship Date"], inplace=True)

    # One-hot encode low-cardinality categorical columns
    # Using pd.get_dummies — correct approach for Linear Regression
    # drop_first=True avoids multicollinearity (dummy variable trap)
    cat_cols = ["Ship Mode", "Segment", "Region", "Category", "Sub-Category"]
    cat_cols = [c for c in cat_cols if c in df.columns]

    print(f"[INFO] One-hot encoding columns: {cat_cols}")
    df = pd.get_dummies(df, columns=cat_cols, drop_first=True)

    # Drop remaining nulls
    df.dropna(inplace=True)

    print(f"[INFO] Final feature count: {df.shape[1] - 1} features")

    # Features & Target
    X = df.drop(columns=["Sales"])
    y = df["Sales"]

    # Log-transform Sales target
    print("[INFO] Applying log1p transform to Sales target...")
    y_log = np.log1p(y)

    # Train-Test Split (80/20)
    X_train, X_test, y_train_log, y_test_log = train_test_split(
        X, y_log, test_size=0.2, random_state=42
    )
    _, y_test_orig = train_test_split(y, test_size=0.2, random_state=42)

    # Feature Scaling
    scaler = StandardScaler()
    X_train = scaler.fit_transform(X_train)
    X_test  = scaler.transform(X_test)

    print(f"[INFO] Train size: {X_train.shape} | Test size: {X_test.shape}")
    return X_train, X_test, y_train_log.values, y_test_log.values, y_test_orig.values



# Step 3: Train Linear Regression Model

def train_model(X_train, y_train_log):
    """Train Linear Regression on log-transformed Sales."""
    print("[INFO] Training Linear Regression model...")
    model = LinearRegression()
    model.fit(X_train, y_train_log)
    print("[INFO] Training complete.")
    return model



# Step 4: Evaluate Model

def evaluate_model(model, X_test, y_test_log, y_test_orig):
    """
    Evaluate in log-scale (R²) and original scale (MAE, RMSE).
    Predictions are inverted with expm1 for real-world interpretability.
    """
    y_pred_log  = model.predict(X_test)
    r2          = r2_score(y_test_log, y_pred_log)

    y_pred_orig = np.expm1(y_pred_log)
    mae         = mean_absolute_error(y_test_orig, y_pred_orig)
    mse         = mean_squared_error(y_test_orig, y_pred_orig)
    rmse        = np.sqrt(mse)

    print("\n========== Linear Regression Evaluation ==========")
    print(f"  MAE  (original scale) : {mae:.4f}")
    print(f"  MSE  (original scale) : {mse:.4f}")
    print(f"  RMSE (original scale) : {rmse:.4f}")
    print(f"  R²   (log scale)      : {r2:.4f}")
    print("===================================================\n")

    return {"Model": "Linear Regression", "MAE": mae, "MSE": mse, "RMSE": rmse, "R2": r2}



# Step 5: Export Predictions for Stacking

def export_predictions(model, X_train, X_test):
    """
    Export train/test predictions (original scale) as CSVs.
    Inverted from log-scale using expm1.
    Passed to Kashvi's stacking meta-model as input features.
    """
    print("[INFO] Exporting predictions for stacking ensemble...")

    train_preds = np.expm1(model.predict(X_train))
    test_preds  = np.expm1(model.predict(X_test))

    pd.DataFrame(train_preds, columns=["lr_prediction"]).to_csv(
        os.path.join(OUTPUT_DIR, "lr_predictions_train.csv"), index=False
    )
    pd.DataFrame(test_preds, columns=["lr_prediction"]).to_csv(
        os.path.join(OUTPUT_DIR, "lr_predictions_test.csv"), index=False
    )

    print("[INFO] Saved: outputs/lr_predictions_train.csv")
    print("[INFO] Saved: outputs/lr_predictions_test.csv")

    return train_preds, test_preds



# Main Pipeline

def main():
    csv_path = download_dataset()
    X_train, X_test, y_train_log, y_test_log, y_test_orig = load_and_preprocess(csv_path)
    model   = train_model(X_train, y_train_log)
    metrics = evaluate_model(model, X_test, y_test_log, y_test_orig)
    export_predictions(model, X_train, X_test)
    print("[DONE] Linear Regression pipeline complete.")
    return model, metrics


if __name__ == "__main__":
    main()